"""Fetch the list of released ROS packages (as shown on index.ros.org).

Uses the rosdistro index and per-distro distribution caches to collect every
released package across all distributions (including EOL ones, which
index.ros.org also lists). Writes index_packages.yaml mapping
package name -> list of distros. convert_to_markdown.py uses this to rewrite
wiki links to packages into https://index.ros.org/p/<package> links.

Usage:
    python3 fetch_index_packages.py [--output index_packages.yaml]
"""
import argparse
import sys

import rosdistro

# Distros in the rosdistro index that index.ros.org does not publish.
EXCLUDED_DISTROS = {"groovy"}


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--output", default="index_packages.yaml")
    args = parser.parse_args()

    index = rosdistro.get_index(rosdistro.get_index_url())
    packages = {}
    for distro in sorted(set(index.distributions) - EXCLUDED_DISTROS):
        try:
            dist = rosdistro.get_cached_distribution(index, distro)
        except Exception as e:
            # Some old caches (e.g. groovy, hydro) contain YAML tags that
            # can't be safely loaded; fall back to the distribution file.
            print(f"Note: {distro} cache unusable ({str(e).splitlines()[0]}); "
                  "using distribution file.")
            try:
                dist = rosdistro.get_distribution(index, distro)
            except Exception as e2:
                print(f"Warning: could not load {distro}: {e2}")
                continue
        names = set(dist.release_packages)
        print(f"{distro}: {len(names)} packages")
        for name in names:
            packages.setdefault(name, []).append(distro)

    if not packages:
        print("Error: no packages found.")
        return 1

    with open(args.output, "w") as f:
        f.write("# Generated by fetch_index_packages.py from the rosdistro cache\n")
        for name in sorted(packages):
            f.write(f"{name}: [{', '.join(sorted(packages[name]))}]\n")
    print(f"Wrote {len(packages)} packages to {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
